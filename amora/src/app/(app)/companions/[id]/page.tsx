/* eslint-disable @next/next/no-img-element */
import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { likeFromProfileAction, unmatchAction } from "@/app/(app)/actions";
import { AiBadge } from "@/components/CompanionCard";
import { BackIcon, BriefcaseIcon, ChatIcon, PinIcon } from "@/components/icons";
import { HeartIcon } from "@/components/Logo";
import { requireUser } from "@/lib/auth";
import { getCompanion, isMatched } from "@/lib/data";
import { themeGradient } from "@/lib/themes";

export async function generateMetadata(props: PageProps<"/companions/[id]">): Promise<Metadata> {
  const { id } = await props.params;
  const c = await getCompanion(id);
  return { title: c ? `${c.name}, ${c.age}` : "Profile" };
}

export default async function CompanionPage(props: PageProps<"/companions/[id]">) {
  const { id } = await props.params;
  const user = await requireUser();
  const companion = await getCompanion(id);
  if (!companion || !companion.isActive) notFound();
  const matched = await isMatched(user.id, companion.id);

  return (
    <main>
      <div className="relative h-[52dvh] min-h-80 overflow-hidden rounded-b-[2rem]" style={{ backgroundImage: themeGradient(companion.theme) }}>
        <div className="absolute inset-0 bg-[radial-gradient(circle_at_50%_35%,rgba(255,255,255,0.3),transparent_60%)]" />
        <img src={companion.avatarUrl} alt={companion.name} className="absolute inset-x-0 top-8 mx-auto h-[88%] object-contain drop-shadow-[0_18px_30px_rgba(0,0,0,0.25)]" />
        <Link href="/discover" aria-label="Back" className="absolute top-4 left-4 grid size-10 place-items-center rounded-full bg-black/35 text-white backdrop-blur-md">
          <BackIcon className="size-5" />
        </Link>
        <AiBadge className="absolute top-5 right-4" />
      </div>

      <section className="px-5 pt-6">
        <h1 className="font-display text-4xl font-semibold">
          {companion.name} <span className="font-sans text-3xl font-light text-muted">{companion.age}</span>
        </h1>
        <div className="mt-2 flex flex-wrap gap-x-4 gap-y-1 text-sm text-muted">
          <span className="inline-flex items-center gap-1.5">
            <BriefcaseIcon className="size-4" /> {companion.occupation}
          </span>
          <span className="inline-flex items-center gap-1.5">
            <PinIcon className="size-4" /> {companion.location}
          </span>
        </div>
        <p className="mt-4 text-lg leading-snug">{companion.tagline}</p>

        <h2 className="mt-8 text-xs font-semibold tracking-widest text-muted uppercase">About me</h2>
        <p className="mt-2 leading-relaxed text-text/90">{companion.bio}</p>

        <h2 className="mt-8 text-xs font-semibold tracking-widest text-muted uppercase">Into</h2>
        <div className="mt-3 flex flex-wrap gap-2">
          {companion.interests.map((i) => (
            <span key={i} className="rounded-full border border-line bg-surface px-3 py-1.5 text-sm">
              {i}
            </span>
          ))}
        </div>

        <div className="mt-8 flex flex-col gap-3">
          {companion.prompts.map((p) => (
            <div key={p.q} className="rounded-3xl border border-line bg-surface p-5">
              <p className="text-sm font-medium text-muted">{p.q}</p>
              <p className="font-display mt-2 text-xl leading-snug">{p.a}</p>
            </div>
          ))}
        </div>

        <p className="mt-8 text-center text-xs text-muted">
          {companion.name} is an AI character. Conversations are generated by AI.
        </p>

        {matched && (
          <form action={unmatchAction.bind(null, companion.id)} className="mt-3 text-center">
            <button type="submit" className="text-sm text-muted underline underline-offset-4 hover:text-text">
              Unmatch and delete chat
            </button>
          </form>
        )}
      </section>

      <div className="sticky bottom-0 z-30 flex justify-center bg-gradient-to-t from-bg via-bg/95 to-transparent px-5 pt-8 pb-4">
        {matched ? (
          <Link href={`/chat/${companion.id}`} className="bg-brand inline-flex h-14 w-full items-center justify-center gap-2 rounded-full font-semibold text-white shadow-xl shadow-accent/30">
            <ChatIcon className="size-5" /> Message {companion.name}
          </Link>
        ) : (
          <form action={likeFromProfileAction.bind(null, companion.id)} className="w-full">
            <button type="submit" className="bg-brand inline-flex h-14 w-full items-center justify-center gap-2 rounded-full font-semibold text-white shadow-xl shadow-accent/30">
              <HeartIcon className="size-5" filled /> Like &amp; start chatting
            </button>
          </form>
        )}
      </div>
    </main>
  );
}
